"use strict";

/**
 * Reads every .wav file in assets/sounds/ and writes src/lwpRingtones.js,
 * a plain JS module exporting each ringtone as a base64 data: URI.
 *
 * The data is inlined (rather than emitted as separate files via a webpack
 * asset loader) so that ringtones work identically whether libwebphone is
 * consumed as the prebuilt dist/libwebphone.js script bundle or imported
 * from src/ by a consumer's own bundler - neither needs any asset-loader
 * configuration, and no network request is ever made to play them.
 *
 * Run this whenever files are added/changed/removed under assets/sounds/:
 *   npm run ringtones:build
 */

const fs = require("fs");
const path = require("path");

const soundsDir = path.resolve(__dirname, "../assets/sounds");
const outputFile = path.resolve(__dirname, "../src/lwpRingtones.js");

function toName(id) {
  return id
    .split(/[-_]/g)
    .map((word) => {
      // "ring01" -> "Ring 1" (insert a space before a trailing digit run
      // and strip leading zeros), rather than "Ring01".
      const match = /^([a-zA-Z]+)(\d+)$/.exec(word);
      if (match) {
        return match[1].charAt(0).toUpperCase() + match[1].slice(1) + " " + parseInt(match[2], 10);
      }
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(" ");
}

const files = fs
  .readdirSync(soundsDir)
  .filter((filename) => filename.toLowerCase().endsWith(".wav"))
  .sort();

if (files.length === 0) {
  throw new Error("No .wav files found in " + soundsDir);
}

const ringtones = files.map((filename) => {
  const id = path.basename(filename, path.extname(filename));
  const data = fs.readFileSync(path.join(soundsDir, filename));

  return {
    id,
    name: toName(id),
    dataUri: "data:audio/wav;base64," + data.toString("base64"),
  };
});

const header = "// This file is generated by scripts/generate-ringtones.js\n" +
  "// Do not edit by hand - add/remove .wav files under assets/sounds/ and rerun\n" +
  "// `npm run ringtones:build` instead.\n" +
  '"use strict";\n\n';

const body = "export default " + JSON.stringify(ringtones, null, 2) + ";\n";

fs.writeFileSync(outputFile, header + body);

console.log(
  "Wrote " + outputFile + " with " + ringtones.length + " ringtone(s): " +
  ringtones.map((r) => r.id).join(", ")
);
